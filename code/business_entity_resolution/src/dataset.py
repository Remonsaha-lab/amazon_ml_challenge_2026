class RecordCache:
    """Pre-computes and caches normalized fields for high-speed feature extraction with full NaN safety."""
    def __init__(self, df: pd.DataFrame):
        self.names = {}
        self.addrs = {}
        self.countries = {}
        self.norm_names = {}
        self.norm_addrs = {}
        self.pins = {}
        self.nums = {}

        for row in df.itertuples(index=False):
            eid = str(row.entity_id)
            raw_name = getattr(row, "business_name", "")
            raw_addr = getattr(row, "business_address", "")
            raw_cntry = getattr(row, "country", "")

            name = "" if is_empty_or_nan(raw_name) else str(raw_name).strip()
            addr = "" if is_empty_or_nan(raw_addr) else str(raw_addr).strip()
            cntry = "" if is_empty_or_nan(raw_cntry) else str(raw_cntry).strip()

            self.names[eid] = name
            self.addrs[eid] = addr
            self.countries[eid] = cntry
            self.norm_names[eid] = normalize_name(name)
            self.norm_addrs[eid] = normalize_address(addr)
            self.pins[eid] = extract_postal_code(addr, cntry)
            self.nums[eid] = extract_numeric_tokens(addr)


def load_ground_truth_map(gt_path: str) -> Dict[str, Set[str]]:
    """Loads ground truth into {source1_entity_id: set_of_matched_ids}."""
    df_gt = pd.read_csv(gt_path, sep="\t", dtype=str)
    df_gt["matched_entity_ids"] = df_gt["matched_entity_ids"].fillna("")
    
    gt_map = {}
    for row in df_gt.itertuples(index=False):
        s1_id = row.source1_entity_id
        raw_m = str(row.matched_entity_ids or "").strip()
        targets = {x.strip() for x in raw_m.split(",") if x.strip()} if raw_m else set()
        gt_map[s1_id] = targets
    return gt_map


def build_pairwise_dataset(
    s1_cache: RecordCache,
    cand_cache: RecordCache,
    candidate_dict: Dict[str, Any],
    gt_map: Dict[str, Set[str]],
    is_training: bool = True,
    hard_neg_ratio: int = 4,
    random_seed: int = 42
) -> Tuple[np.ndarray, np.ndarray, List[Tuple[str, str]]]:
    """
    Constructs feature matrix X, binary labels y, and (s1_id, cand_id) pair tuples.
    - Strictly avoids GT injection: only pairs actually retrieved by blocking are trained on.
    - True hard negatives: prioritizes non-matching candidates with highest blocking similarity/IBF.
    - For validation, evaluates all candidates generated by blocking without subsampling.
    """
    rng = np.random.RandomState(random_seed)
    features_list = []
    labels_list = []
    pairs_list = []

    for s1_id, raw_candidate_set in tqdm(candidate_dict.items(), desc="Extracting Pair Features"):
        true_matches = gt_map.get(s1_id, set())
        
        # Preserve ranked order if list, or convert to list
        cand_list = list(raw_candidate_set)
        
        # Partition candidates into positives and negatives strictly from blocker output
        pos_cands = [c for c in cand_list if c in true_matches and c in cand_cache.names]
        neg_cands = [c for c in cand_list if c not in true_matches and c in cand_cache.names]

        # For training: ONLY use candidates produced by blocker (NO artificial GT injection)
        if is_training:
            if not pos_cands:
                # If singleton or no positive matches retrieved, keep top 2 hard negatives
                selected_negs = neg_cands[:2]
            else:
                max_negs = max(len(pos_cands) * hard_neg_ratio, 2)
                # Genuine Hard Negatives: cand_list is ordered by descending IBF / similarity score
                # Taking the top neg_cands yields the highest-ranked false positives from blocking
                selected_negs = neg_cands[:max_negs]

            eval_pairs = [(c, 1.0) for c in pos_cands] + [(c, 0.0) for c in selected_negs]
        else:
            # For validation: evaluate all candidates produced by blocking that exist in cache
            eval_pairs = [(c, 1.0 if c in true_matches else 0.0) for c in cand_list if c in cand_cache.names]

        # Extract features for each pair
        for cand_id, label in eval_pairs:
            feat_vec = compute_pair_features(
                s1_name=s1_cache.names[s1_id],
                s1_addr=s1_cache.addrs[s1_id],
                s1_country=s1_cache.countries[s1_id],
                cand_id=cand_id,
                cand_name=cand_cache.names[cand_id],
                cand_addr=cand_cache.addrs[cand_id],
                cand_country=cand_cache.countries[cand_id],
                s1_norm_name=s1_cache.norm_names[s1_id],
                s1_norm_addr=s1_cache.norm_addrs[s1_id],
                s1_pin=s1_cache.pins[s1_id],
                s1_nums=s1_cache.nums[s1_id],
                cand_norm_name=cand_cache.norm_names[cand_id],
                cand_norm_addr=cand_cache.norm_addrs[cand_id],
                cand_pin=cand_cache.pins[cand_id],
                cand_nums=cand_cache.nums[cand_id]
            )
            features_list.append(feat_vec)
            labels_list.append(label)
            pairs_list.append((s1_id, cand_id))

    X = np.array(features_list, dtype=np.float32)
    y = np.array(labels_list, dtype=np.float32)
    return X, y, pairs_list
