def transliterate_indic(text: str) -> str:
    res = []
    for ch in text:
        if ch in DEVANAGARI_MAP:
            res.append(DEVANAGARI_MAP[ch])
        elif ch in KANNADA_MAP:
            res.append(KANNADA_MAP[ch])
        elif ch in TAMIL_MAP:
            res.append(TAMIL_MAP[ch])
        else:
            res.append(ch)
    return "".join(res)

