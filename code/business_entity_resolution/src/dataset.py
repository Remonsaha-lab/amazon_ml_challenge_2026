class RecordCache:
    """Pre-computes and caches normalized fields for high-speed feature extraction with full NaN safety.
    Stores normalized strings directly, eliminating redundant duplicate string objects in memory.
    Supports both pandas DataFrames and raw record tuples (entity_id, name, addr, country).
    """
    def __init__(self, data: Any):
        self.norm_names: Dict[str, str] = {}
        self.norm_addrs: Dict[str, str] = {}
        self.countries: Dict[str, str] = {}
        self.pins: Dict[str, Optional[str]] = {}
        self.nums: Dict[str, Set[str]] = {}

        if isinstance(data, pd.DataFrame):
            iterator = [
                (str(r.entity_id), getattr(r, "business_name", ""), getattr(r, "business_address", ""), getattr(r, "country", ""))
                for r in data.itertuples(index=False)
            ]
        elif isinstance(data, list):
            iterator = data
        else:
            iterator = list(data)

        for item in iterator:
            if len(item) < 4:
                continue
            eid = str(item[0]).strip()
            raw_name = item[1]
            raw_addr = item[2]
            raw_cntry = item[3]

            name = "" if is_empty_or_nan(raw_name) else str(raw_name).strip()
            addr = "" if is_empty_or_nan(raw_addr) else str(raw_addr).strip()
            cntry = "" if is_empty_or_nan(raw_cntry) else str(raw_cntry).strip()

            c_norm = normalize_country(cntry)
            self.countries[eid] = c_norm
            self.norm_names[eid] = normalize_name(name)
            self.norm_addrs[eid] = normalize_address(addr)
            self.pins[eid] = extract_postal_code(addr, cntry)
            self.nums[eid] = extract_numeric_tokens(addr)

        # Backward compatibility pointers to save memory
        self.names = self.norm_names
        self.addrs = self.norm_addrs

    def clear(self):
        """Release cached dictionaries from RAM."""
        self.norm_names.clear()
        self.norm_addrs.clear()
        self.countries.clear()
        self.pins.clear()
        self.nums.clear()
        gc.collect()


def load_ground_truth_map(gt_path: str) -> Dict[str, Set[str]]:
    """Loads ground truth into {source1_entity_id: set_of_matched_ids}."""
    df_gt = pd.read_csv(gt_path, sep="\t", dtype=str)
    df_gt["matched_entity_ids"] = df_gt["matched_entity_ids"].fillna("")
    
    gt_map = {}
    for row in df_gt.itertuples(index=False):
        s1_id = row.source1_entity_id
        raw_m = str(row.matched_entity_ids or "").strip()
        targets = {x.strip() for x in raw_m.split(",") if x.strip()} if raw_m else set()
        gt_map[s1_id] = targets
    return gt_map


def build_pairwise_dataset(
    s1_cache: RecordCache,
    cand_cache: RecordCache,
    candidate_dict: Dict[str, Any],
    gt_map: Dict[str, Set[str]],
    is_training: bool = True,
    hard_neg_ratio: int = 4,
    random_seed: int = 42,
    show_progress: bool = True
) -> Tuple[np.ndarray, np.ndarray, List[Tuple[str, str]]]:
    """
    Constructs feature matrix X, binary labels y, and (s1_id, cand_id) pair tuples.
    - Strictly avoids GT injection: only pairs actually retrieved by blocking are trained on.
    - True hard negatives: prioritizes non-matching candidates with highest blocking similarity/IBF.
    - For validation, evaluates all candidates generated by blocking without subsampling.
    """
    features_list = []
    labels_list = []
    pairs_list = []

    iterator = candidate_dict.items()
    if show_progress:
        iterator = tqdm(iterator, total=len(candidate_dict), desc="Extracting Pair Features")

    for s1_id, raw_candidate_set in iterator:
        true_matches = gt_map.get(s1_id, set())
        cand_list = list(raw_candidate_set)
        
        pos_cands = [c for c in cand_list if c in true_matches and c in cand_cache.norm_names]
        neg_cands = [c for c in cand_list if c not in true_matches and c in cand_cache.norm_names]

        if is_training:
            if not pos_cands:
                selected_negs = neg_cands[:2]
            else:
                max_negs = max(len(pos_cands) * hard_neg_ratio, 2)
                selected_negs = neg_cands[:max_negs]

            eval_pairs = [(c, 1.0) for c in pos_cands] + [(c, 0.0) for c in selected_negs]
        else:
            eval_pairs = [(c, 1.0 if c in true_matches else 0.0) for c in cand_list if c in cand_cache.norm_names]

        s1_n = s1_cache.norm_names.get(s1_id, "")
        s1_a = s1_cache.norm_addrs.get(s1_id, "")
        s1_c = s1_cache.countries.get(s1_id, "")
        s1_p = s1_cache.pins.get(s1_id)
        s1_num = s1_cache.nums.get(s1_id, set())

        for cand_id, label in eval_pairs:
            feat_vec = compute_pair_features(
                s1_name="",
                s1_addr="",
                s1_country=s1_c,
                cand_id=cand_id,
                cand_name="",
                cand_addr="",
                cand_country=cand_cache.countries.get(cand_id, ""),
                s1_norm_name=s1_n,
                s1_norm_addr=s1_a,
                s1_pin=s1_p,
                s1_nums=s1_num,
                cand_norm_name=cand_cache.norm_names.get(cand_id, ""),
                cand_norm_addr=cand_cache.norm_addrs.get(cand_id, ""),
                cand_pin=cand_cache.pins.get(cand_id),
                cand_nums=cand_cache.nums.get(cand_id, set())
            )
            features_list.append(feat_vec)
            labels_list.append(label)
            pairs_list.append((s1_id, cand_id))

    if features_list:
        X = np.array(features_list, dtype=np.float32)
        y = np.array(labels_list, dtype=np.float32)
    else:
        X = np.empty((0, len(FEATURE_NAMES)), dtype=np.float32)
        y = np.empty((0,), dtype=np.float32)

    return X, y, pairs_list


class ChunkedDatasetBuilder:
    """
    Builds pairwise training datasets in memory-safe chunks.
    Processes S1 entities in blocks of size `chunk_size` (e.g. 10,000 entities),
    generating candidates and extracting pairwise features without memory spikes.
    """
    def __init__(
        self,
        chunk_size: int = 10000,
        max_cands: int = 50,
        hard_neg_ratio: int = 4,
        random_seed: int = 42
    ):
        self.chunk_size = chunk_size
        self.max_cands = max_cands
        self.hard_neg_ratio = hard_neg_ratio
        self.random_seed = random_seed

    def process_s1_chunks(
        self,
        s1_tuples: List[Tuple[str, str, str, str]],
        cand_cache: RecordCache,
        blocker: MultiKeyBlocker,
        gt_map: Dict[str, Set[str]],
        is_training: bool = True,
        desc: str = "Processing Chunks"
    ) -> Tuple[np.ndarray, np.ndarray, List[Tuple[str, str]]]:
        """
        Processes list of (s1_id, name, addr, country) in chunks of `chunk_size`.
        Extracts features incrementally and concatenates final matrices.
        """
        all_X = []
        all_y = []
        all_pairs = []

        total_chunks = (len(s1_tuples) + self.chunk_size - 1) // self.chunk_size

        for chunk_idx in range(total_chunks):
            start = chunk_idx * self.chunk_size
            end = min(start + self.chunk_size, len(s1_tuples))
            chunk_s1 = s1_tuples[start:end]

            # Build small cache for this S1 chunk only
            s1_chunk_cache = RecordCache(chunk_s1)

            # Generate candidate pairs via blocker
            candidate_dict = {}
            for s1_id, name, addr, cntry in chunk_s1:
                candidate_dict[s1_id] = blocker.retrieve_candidates_for_record(s1_id, name, addr, cntry)

            # Extract features for this chunk
            X_chunk, y_chunk, pairs_chunk = build_pairwise_dataset(
                s1_chunk_cache,
                cand_cache,
                candidate_dict,
                gt_map,
                is_training=is_training,
                hard_neg_ratio=self.hard_neg_ratio,
                random_seed=self.random_seed,
                show_progress=False
            )

            if len(X_chunk) > 0:
                all_X.append(X_chunk)
                all_y.append(y_chunk)
                all_pairs.extend(pairs_chunk)

            # Clean chunk cache
            s1_chunk_cache.clear()
            del s1_chunk_cache, candidate_dict
            gc.collect()

        if all_X:
            X_final = np.vstack(all_X)
            y_final = np.concatenate(all_y)
        else:
            X_final = np.empty((0, len(FEATURE_NAMES)), dtype=np.float32)
            y_final = np.empty((0,), dtype=np.float32)

        return X_final, y_final, all_pairs
