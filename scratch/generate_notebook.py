    "    res = []\n",
    "    for ch in str(text):\n",
    "        if ('\\u00c0' <= ch <= '\\u024f') or ('\\u1e00' <= ch <= '\\u1eff'):\n",
    "            decomp = unicodedata.normalize(\"NFKD\", ch)\n",
