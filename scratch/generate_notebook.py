    "def evaluate_macro_f05(truth: Dict[str, Set[str]], pred: Dict[str, Set[str]]) -> Tuple[float, float, float]:\n",
    "    \"\"\"Calculate official Macro F0.5, Mean Precision, and Mean Recall metrics.\"\"\"\n",
    "    precisions, recalls, f05s = [], [], []\n",
    "    for sid, t_set in truth.items():\n",
    "        p_set = pred.get(sid, set())\n",
