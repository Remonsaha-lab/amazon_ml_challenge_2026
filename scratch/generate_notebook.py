    "# Inverted Index Multi-Key Union Blocker\n",
    "class MultiKeyBlocker:\n",
    "    \"\"\"\n",
    "    Multi-Key Inverted Index Blocker with 8 blocking key strategies (B1-B8),\n",
    "    using compact uint32 postings list arrays ('I') for low RAM consumption.\n",
    "    \"\"\"\n",
    "    def __init__(self, max_candidates_per_s1: int = 100):\n",
    "        self.max_candidates = max_candidates_per_s1\n",
    "        self.index = defaultdict(lambda: array('I'))\n",
    "        self.candidate_ids = []\n",
    "        self.cand_id_to_idx = {}\n",
    "\n",
    "    def generate_blocking_keys(self, name: str, address: str, country: str) -> Set[str]:\n",
    "        keys = set()\n",
    "        norm_name = normalize_name(name)\n",
    "        norm_addr = normalize_address(address)\n",
    "        norm_cntry = normalize_country(country)\n",
    "        pin = extract_postal_code(address, country)\n",
    "        nums = extract_numeric_tokens(address)\n",
    "        \n",
    "        # B1: Clean exact name + country\n",
    "        if norm_name:\n",
    "            keys.add(f\"B1:{norm_name}|{norm_cntry}\")\n",
    "        \n",
    "        # B2: Name token prefix combo\n",
    "        tokens = norm_name.split()\n",
    "        if tokens:\n",
    "            first_tok = tokens[0]\n",
    "            if len(first_tok) >= 3:\n",
    "                keys.add(f\"B2:{first_tok[:4]}|{norm_cntry}\")\n",
    "            if len(tokens) >= 2:\n",
    "                second_tok = tokens[1]\n",
    "                keys.add(f\"B2_DUAL:{first_tok[:3]}_{second_tok[:3]}|{norm_cntry}\")\n",
    "                \n",
    "        # B3: Postal PIN code + country\n",
    "        if pin:\n",
    "            keys.add(f\"B3:{pin}|{norm_cntry}\")\n",
    "            if norm_name and len(norm_name) >= 3:\n",
    "                keys.add(f\"B3_NAME:{pin}_{norm_name[:3]}|{norm_cntry}\")\n",
    "                \n",
    "        # B4: Numeric building/street tokens + first name token\n",
    "        if nums and tokens:\n",
    "            for num in list(nums)[:2]:\n",
    "                keys.add(f\"B4:{tokens[0][:3]}_{num}|{norm_cntry}\")\n",
    "                \n",
    "        # B5: Subword character 3-grams for typo resilience\n",
    "        if norm_name and len(norm_name) >= 4:\n",
    "            clean_name_nospace = norm_name.replace(\" \", \"\")\n",
    "            for i in range(min(len(clean_name_nospace) - 2, 4)):\n",
    "                gram = clean_name_nospace[i:i+3]\n",
    "                keys.add(f\"B5:{gram}|{norm_cntry}\")\n",
    "                \n",
    "        # B6: Locality & Street token + PIN\n",
    "        addr_tokens = norm_addr.split()\n",
    "        if addr_tokens and pin:\n",
    "            for atok in addr_tokens:\n",
    "                if len(atok) >= 4 and not atok.isdigit():\n",
    "                    keys.add(f\"B6:{pin}_{atok[:4]}|{norm_cntry}\")\n",
    "                    break\n",
    "                    \n",
